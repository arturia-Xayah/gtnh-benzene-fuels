package dev.benzenefuels;

import java.util.EnumMap;
import java.util.List;
import java.util.Map;

import net.minecraft.block.Block;
import net.minecraft.client.renderer.texture.IIconRegister;
import net.minecraft.creativetab.CreativeTabs;
import net.minecraft.entity.player.EntityPlayer;
import net.minecraft.item.Item;
import net.minecraft.item.ItemStack;
import net.minecraft.util.IIcon;
import net.minecraft.util.ResourceLocation;
import net.minecraft.util.StatCollector;
import net.minecraftforge.fluids.Fluid;
import net.minecraftforge.fluids.FluidRegistry;
import net.minecraftforge.fluids.FluidStack;

import cpw.mods.fml.common.registry.GameRegistry;
import cpw.mods.fml.relauncher.Side;
import cpw.mods.fml.relauncher.SideOnly;
import gregtech.api.enums.FluidState;
import gregtech.api.enums.ItemList;
import gregtech.api.fluid.GTFluidFactory;
import gtPlusPlus.xmod.gregtech.common.tileentities.machines.multi.production.chemplant.MTEChemicalPlant;

public final class FuelContent {

    private static final Map<FuelStage, Fluid> FLUIDS = new EnumMap<>(FuelStage.class);
    private static final Map<GeneratorRoute, Fluid[]> BASE_FLUIDS = new EnumMap<>(GeneratorRoute.class);
    public static final int STAR_META = 100;
    public static final int EXPONENT_META = 200;
    public static final int BASE_CELL_META = 400;
    public static final int CATALYST_META = 30000;
    public static Item components;
    public static Fluid uvActivator;
    public static Block resonanceLightCasing;

    private FuelContent() {}

    public static void register() {
        resonanceLightCasing = new ResonanceLightCasing().setBlockName("benzenefuels.resonance_light_casing")
            .setBlockTextureName("benzenefuels:resonance_light_casing")
            .setCreativeTab(CreativeTabs.tabBlock)
            .setHardness(5.0F)
            .setResistance(10.0F)
            .setLightLevel(1.0F);
        GameRegistry.registerBlock(resonanceLightCasing, "resonance_light_casing");
        for (FuelStage stage : FuelStage.values()) {
            ResourceLocation texture = new ResourceLocation(stage.fluidTexture());
            FLUIDS.put(
                stage,
                GTFluidFactory.builder(stage.fluidId())
                    .withDefaultLocalName(stage.englishName)
                    .withStateAndTemperature(FluidState.LIQUID, 300)
                    .withTextures(texture, texture)
                    .withColorRGBA(new short[] { 255, 255, 255, 255 })
                    .buildAndRegister()
                    .asFluid());
        }
        uvActivator = fluid("benzenefuels.uv_activator", "UV Benzene Activator", 0xB8B3FF);
        for (GeneratorRoute route : GeneratorRoute.values()) {
            Fluid[] fluids = new Fluid[5];
            for (int mk = 1; mk <= 5; mk++) fluids[mk - 1] = fluid(
                route.baseFluidId(mk),
                route.name() + " Base Fluid Mk" + mk,
                route == GeneratorRoute.TECHNOLOGY ? 0x8DD8FF : 0xC9A4FF);
            BASE_FLUIDS.put(route, fluids);
        }
        components = new Components();
        GameRegistry.registerItem(components, "components");
    }

    private static Fluid fluid(String id, String name, int color) {
        if (FluidRegistry.isFluidRegistered(id)) throw new IllegalStateException("Fluid ID already in use: " + id);
        return GTFluidFactory.builder(id)
            .withDefaultLocalName(name)
            .withStateAndTemperature(FluidState.LIQUID, 300)
            .withTextureName("autogenerated")
            .withColorRGBA(
                new short[] { (short) (color >> 16 & 255), (short) (color >> 8 & 255), (short) (color & 255), 255 })
            .buildAndRegister()
            .asFluid();
    }

    public static void registerContainers() {
        for (FuelStage stage : FuelStage.values()) {
            registerCell(stack(stage, 1000), cell(stage, 1));
        }
        for (GeneratorRoute route : GeneratorRoute.values())
            for (int mk = 1; mk <= 5; mk++) registerCell(baseFluid(route, mk, 1000), baseCell(route, mk, 1));
        MTEChemicalPlant.registerChemplantCatalyst(catalyst(1));
    }

    private static void registerCell(FluidStack fluid, ItemStack cell) {
        if (!net.minecraftforge.fluids.FluidContainerRegistry
            .registerFluidContainer(fluid, cell, ItemList.Cell_Empty.get(1)))
            throw new IllegalStateException(
                "Cannot register cell: " + fluid.getFluid()
                    .getName());
        gregtech.api.enums.GTValues.RA.stdBuilder()
            .itemInputs(ItemList.Cell_Empty.get(1))
            .itemOutputs(cell)
            .fluidInputs(fluid)
            .duration(16)
            .eut(1)
            .addTo(gregtech.api.recipe.RecipeMaps.cannerRecipes);
        gregtech.api.enums.GTValues.RA.stdBuilder()
            .itemInputs(cell)
            .itemOutputs(ItemList.Cell_Empty.get(1))
            .fluidOutputs(fluid)
            .duration(16)
            .eut(1)
            .addTo(gregtech.api.recipe.RecipeMaps.cannerRecipes);
    }

    public static FluidStack stack(FuelStage stage, int liters) {
        return new FluidStack(FLUIDS.get(stage), liters);
    }

    public static ItemStack cell(FuelStage stage, int count) {
        return new ItemStack(components, count, stage.ordinal() + 1);
    }

    public static ItemStack activator(int count) {
        return new ItemStack(components, count, 0);
    }

    public static ItemStack catalyst(int count) {
        return new ItemStack(components, count, CATALYST_META);
    }

    public static ItemStack star(VoltageStar stage, int count) {
        return new ItemStack(components, count, STAR_META + stage.ordinal());
    }

    public static ItemStack exponentCore(GeneratorRoute route, int mk, int count) {
        route.exponent(mk);
        return new ItemStack(components, count, EXPONENT_META + route.ordinal() * 10 + mk - 1);
    }

    public static FluidStack baseFluid(GeneratorRoute route, int mk, int liters) {
        route.base(mk);
        return new FluidStack(BASE_FLUIDS.get(route)[mk - 1], liters);
    }

    public static ItemStack baseCell(GeneratorRoute route, int mk, int count) {
        route.base(mk);
        return new ItemStack(components, count, BASE_CELL_META + route.ordinal() * 10 + mk - 1);
    }

    private static boolean routeMeta(int meta, int start) {
        int offset = meta - start;
        return offset >= 0 && offset < 20 && offset % 10 < 5;
    }

    private static final class Components extends Item {

        private IIcon cellIcon, catalystIcon, starIcon;
        private IIcon[] fuelIcons;

        Components() {
            setHasSubtypes(true);
            setMaxDamage(0);
            setUnlocalizedName("benzenefuels.component");
            setTextureName("minecraft:blaze_powder");
            setCreativeTab(CreativeTabs.tabMaterials);
        }

        @Override
        @SideOnly(Side.CLIENT)
        public void registerIcons(IIconRegister register) {
            super.registerIcons(register);
            cellIcon = register.registerIcon("minecraft:bucket_water");
            catalystIcon = register.registerIcon("minecraft:ender_eye");
            starIcon = register.registerIcon("minecraft:nether_star");
            fuelIcons = new IIcon[FuelStage.values().length];
            for (FuelStage stage : FuelStage.values()) {
                fuelIcons[stage.ordinal()] = register.registerIcon(stage.cellTexture());
            }
        }

        @Override
        @SideOnly(Side.CLIENT)
        public IIcon getIconFromDamage(int meta) {
            if (meta == CATALYST_META) return catalystIcon;
            if (meta >= STAR_META && meta < STAR_META + VoltageStar.values().length) return starIcon;
            if (routeMeta(meta, EXPONENT_META)) return catalystIcon;
            if (routeMeta(meta, BASE_CELL_META)) return cellIcon;
            return meta >= 1 && meta <= FuelStage.values().length ? fuelIcons[meta - 1] : itemIcon;
        }

        @Override
        @SideOnly(Side.CLIENT)
        public int getColorFromItemStack(ItemStack stack, int pass) {
            int meta = stack.getItemDamage();
            if (routeMeta(meta, BASE_CELL_META)) return (meta - BASE_CELL_META) / 10 == 0 ? 0x8DD8FF : 0xC9A4FF;
            if (routeMeta(meta, EXPONENT_META)) return (meta - EXPONENT_META) / 10 == 0 ? 0x8DD8FF : 0xC9A4FF;
            // Fuel sprites contain their final palette; tinting would also recolor the metal cell shell.
            return 0xFFFFFF;
        }

        @Override
        public String getUnlocalizedName(ItemStack stack) {
            int meta = stack.getItemDamage();
            if (meta == 0) return "item.benzenefuels.activator";
            if (meta == CATALYST_META) return "item.benzenefuels.quantum_catalyst";
            if (meta >= STAR_META && meta < STAR_META + VoltageStar.values().length)
                return "item.benzenefuels.star." + VoltageStar.values()[meta - STAR_META].key();
            if (routeMeta(meta, EXPONENT_META)) {
                int offset = meta - EXPONENT_META;
                return "item.benzenefuels.exponent." + GeneratorRoute.values()[offset / 10].key
                    + ".mk"
                    + (offset % 10 + 1);
            }
            if (routeMeta(meta, BASE_CELL_META)) {
                int offset = meta - BASE_CELL_META;
                return "item.benzenefuels.base_cell." + GeneratorRoute.values()[offset / 10].key
                    + ".mk"
                    + (offset % 10 + 1);
            }
            if (meta >= 1 && meta <= FuelStage.values().length)
                return "item.benzenefuels.cell." + FuelStage.values()[meta - 1].key;
            return "item.benzenefuels.unknown";
        }

        @Override
        @SuppressWarnings({ "rawtypes", "unchecked" })
        public void getSubItems(Item item, CreativeTabs tab, List items) {
            items.add(activator(1));
            items.add(catalyst(1));
            for (FuelStage stage : FuelStage.values()) items.add(cell(stage, 1));
            for (VoltageStar stage : VoltageStar.values()) items.add(star(stage, 1));
            for (GeneratorRoute route : GeneratorRoute.values()) for (int mk = 1; mk <= 5; mk++) {
                items.add(exponentCore(route, mk, 1));
                items.add(baseCell(route, mk, 1));
            }
        }

        @Override
        @SuppressWarnings({ "rawtypes", "unchecked" })
        public void addInformation(ItemStack stack, EntityPlayer player, List lines, boolean advanced) {
            int meta = stack.getItemDamage();
            if (meta >= 1 && meta <= FuelStage.values().length) {
                FuelStage stage = FuelStage.values()[meta - 1];
                java.util.Collections.addAll(lines, FuelDescription.lines(stage));
            } else if (meta == CATALYST_META) {
                lines.add(StatCollector.translateToLocal("tooltip.benzenefuels.catalyst"));
            } else if (meta == 0) {
                lines.add(StatCollector.translateToLocal("tooltip.benzenefuels.activator"));
            } else if (meta >= STAR_META && meta < STAR_META + VoltageStar.values().length) {
                VoltageStar stage = VoltageStar.values()[meta - STAR_META];
                lines.add(StatCollector.translateToLocal("tooltip.benzenefuels.star"));
                lines.add(stage.componentsEach() + " / " + stage.durationTicks() / 20 + " s");
            } else if (routeMeta(meta, EXPONENT_META)) {
                int offset = meta - EXPONENT_META;
                lines.add("e = " + GeneratorRoute.values()[offset / 10].exponent(offset % 10 + 1));
                lines.add(StatCollector.translateToLocal("tooltip.benzenefuels.exponent_upgrade"));
                lines.add(StatCollector.translateToLocal("tooltip.benzenefuels.pending_recipe"));
            } else if (routeMeta(meta, BASE_CELL_META)) {
                int offset = meta - BASE_CELL_META;
                lines.add("1,000 L | B = " + GeneratorRoute.values()[offset / 10].base(offset % 10 + 1));
                lines.add(StatCollector.translateToLocal("tooltip.benzenefuels.pending_recipe"));
            }
        }
    }
}
